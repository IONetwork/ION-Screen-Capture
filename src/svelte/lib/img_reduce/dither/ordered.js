/**
 * Ordered (Bayer) dithering.
 *
 * Worth having for a reason specific to a screen-capture tool: error diffusion
 * is globally coupled, so changing one source pixel changes every output pixel
 * downstream in scan order. Flipping between two nearly-identical captures
 * makes the whole frame crawl. Ordered dithering is content-local and
 * position-deterministic, so an unchanged region dithers identically every
 * time. It is also the only mode here that is trivially parallelisable.
 *
 * A subtlety that is easy to get wrong: ordered dithering on a regular lattice
 * is exact (perturb by half a step, then snap). On an arbitrary palette there
 * is no single "step", so the perturbation is scaled per-pixel by the distance
 * from the chosen entry to *its* nearest neighbour. That is a principled
 * approximation, not an exact method, and it is documented as such.
 */

import { strengthFn } from './common.js';

/**
 * Bayer threshold matrix, generated by recursive doubling rather than a literal
 * table. M1 = [[0,2],[3,1]]; M2n = [[4M, 4M+2], [4M+3, 4M+1]].
 * @param {number} size power-of-two side length (2, 4, 8, 16, ...)
 * @returns {{size:number,values:Float64Array}} values in [-0.5, 0.5)
 */
export function bayerMatrix(size = 8) {
  let s = 2;
  let m = [0, 2, 3, 1];
  while (s < size) {
    const ns = s * 2;
    const nm = new Array(ns * ns);
    for (let y = 0; y < s; y++) {
      for (let x = 0; x < s; x++) {
        const v = m[y * s + x] * 4;
        nm[y * ns + x] = v;
        nm[y * ns + (x + s)] = v + 2;
        nm[(y + s) * ns + x] = v + 3;
        nm[(y + s) * ns + (x + s)] = v + 1;
      }
    }
    m = nm; s = ns;
  }
  const n = s * s;
  const values = new Float64Array(n);
  for (let i = 0; i < n; i++) values[i] = (m[i] + 0.5) / n - 0.5;
  return { size: s, values };
}

/** Per-entry distance to its nearest other entry, in working space. */
function entrySpacing(palWork, n) {
  const out = new Float64Array(n);
  for (let i = 0; i < n; i++) {
    const o = i * 3;
    let bd = Infinity;
    for (let j = 0; j < n; j++) {
      if (j === i) continue;
      const p = j * 3;
      const d0 = palWork[o] - palWork[p];
      const d1 = palWork[o + 1] - palWork[p + 1];
      const d2 = palWork[o + 2] - palWork[p + 2];
      const d = d0 * d0 + d1 * d1 + d2 * d2;
      if (d < bd) bd = d;
    }
    out[i] = bd === Infinity ? 0 : Math.sqrt(bd);
  }
  return out;
}

/**
 * @param {Object} image
 * @param {import('../search/nearest.js').Nearest} nearest
 * @param {Float64Array} palWork
 * @param {import('../color/space.js').Space} space
 * @param {Uint8Array} indices
 * @param {Object} opts
 * @param {number} [opts.matrixSize=8]
 * @param {number} [opts.strength=1]
 * @param {Float32Array|null} [opts.edge]
 * @param {number} [opts.edgeSuppression=0]
 * @param {Uint8Array|null} [opts.skip]
 */
export function ditherOrdered(image, nearest, palWork, space, indices, opts = {}) {
  const { data, width, height } = image;
  const channels = image.channels ?? (data.length / (width * height));
  const n = palWork.length / 3;
  const { size, values } = bayerMatrix(opts.matrixSize ?? 8);
  const spacing = entrySpacing(palWork, n);
  const skip = opts.skip ?? null;
  const strengthAt = strengthFn(opts, opts.edge ?? null);

  const px = new Float64Array(3);

  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const p = y * width + x;
      if (skip && skip[p]) { indices[p] = 0; continue; }
      const k = p * channels;

      space.fromRGB8(data[k], data[k + 1], data[k + 2], px, 0);

      // which entry would we pick undithered, and how far apart are entries there
      const idx0 = nearest.findContinuous(px[0], px[1], px[2]);
      const q = idx0 * 3;
      const e0 = px[0] - palWork[q], e1 = px[1] - palWork[q + 1], e2 = px[2] - palWork[q + 2];
      const err = Math.sqrt(e0 * e0 + e1 * e1 + e2 * e2);

      // Scale the perturbation by the actual quantisation error, not just the
      // palette spacing. A pixel that already sits exactly on a palette entry
      // has nothing to dither, and perturbing it anyway would break lossless
      // passthrough for an image that already fits the palette.
      const gap = spacing[idx0];
      const scale = gap > 0 ? Math.min(1, err / gap) : 0;
      const step = gap * scale * strengthAt(p);

      if (step > 0) {
        const t = values[(y % size) * size + (x % size)];
        px[0] += t * step;
        px[1] += t * step;
        px[2] += t * step;
        indices[p] = nearest.findContinuous(px[0], px[1], px[2]);
      } else {
        indices[p] = idx0;
      }
    }
  }
}
